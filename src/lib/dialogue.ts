export function getNpcDialogue(missionId: string, action?: string) {
  const dialogue = dialogues[missionId];
  if (!dialogue) return 'Рады встрече, курьер!';
  return action ? dialogue.replies[action] ?? 'Спасибо за помощь. Счастливого пути!' : dialogue.greeting;
}
